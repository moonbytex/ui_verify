def action_system_prompt(device_type: str, emu_direction: int | None) -> str:
    """hc()"""
    r = ""
    if emu_direction is not None:
        r = f"\n    当前模拟器物理方向={emu_direction}（0=竖屏，1=向右旋转90°，2=旋转180°，3=向左旋转90°=横屏）。"
    n = device_type.strip().lower()
    if n == "2in1":
        return f"""{ACTION_BASE}

当前设备类型为 {device_type}。
对于 2in1、2in1_Foldable 设备，当测试计划没有明确说明是触控操作还是鼠标操作，而只是使用“点击”“双击”“滑动”等通用术语时，默认优先使用鼠标操作。
如果测试计划明确要求触控操作，则必须使用触控工具；如果明确要求鼠标操作，则必须使用鼠标工具。
在以上约束下，2in1、2in1_Foldable 设备允许测试计划同时包含触控和鼠标操作。{r}"""
    if n == "tablet":
        return f"""{ACTION_BASE}

当前设备类型为 tablet。
对于 tablet 设备，当测试计划没有明确说明是触控操作还是鼠标操作，而只是使用“点击”“双击”“滑动”等通用术语时，默认优先使用触控操作。
如果测试计划明确要求鼠标操作，则必须使用鼠标工具；如果明确要求触控操作，则必须使用触控工具。
在以上约束下，tablet 设备允许测试计划同时包含触控和鼠标操作。{r}"""
    return f"{ACTION_BASE}{r}"


